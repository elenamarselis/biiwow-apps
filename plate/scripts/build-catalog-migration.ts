// Regenerates supabase/migrations/*_catalog.sql from data/catalog.json.
// Run: npm run db:catalog
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

type Item = {
  id: string; name: string; kind: string; state: string | null; basis: string; density?: number;
  source_ref?: string; nutrients: Record<string, number>; portions?: { label: string; amount: number }[];
  default_amount: number; max_amount: number; tags: string[]; allergens: string[];
};
const root = join(__dirname, '..');
const items: Item[] = JSON.parse(readFileSync(join(root, 'data/catalog.json'), 'utf8'));
const q = (s: string | null | undefined) => (s === null || s === undefined ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a: string[]) => `array[${a.map(q).join(',')}]::text[]`;
const rows = items.map((i) => {
  const source = /usda/i.test(i.source_ref ?? '') ? 'usda' : 'label';
  return `(${[q(i.id), q(i.name), q(i.kind), q(i.state), q(i.basis), i.density ?? 'null', q(source), q(i.source_ref ?? null),
    q(JSON.stringify(i.nutrients)) + '::jsonb', q(JSON.stringify(i.portions ?? [])) + '::jsonb', i.default_amount, i.max_amount,
    arr(i.tags), arr(i.allergens)].join(', ')})`;
});
const sql = `-- Generated by scripts/build-catalog-migration.ts from data/catalog.json. Do not edit by hand.
-- Generic foods and drinks with values from USDA FoodData Central (per 100 g or 100 ml).
insert into public.catalog_foods (id, name, kind, state, basis, density, source, source_ref, nutrients, portions, default_amount, max_amount, tags, allergens) values
${rows.join(',\n')}
on conflict (id) do update set name = excluded.name, kind = excluded.kind, state = excluded.state, basis = excluded.basis,
  density = excluded.density, source = excluded.source, source_ref = excluded.source_ref, nutrients = excluded.nutrients,
  portions = excluded.portions, default_amount = excluded.default_amount, max_amount = excluded.max_amount,
  tags = excluded.tags, allergens = excluded.allergens;
`;
writeFileSync(join(root, 'supabase/migrations/20261114000002_catalog.sql'), sql);
console.log(`Wrote ${items.length} catalog foods.`);
